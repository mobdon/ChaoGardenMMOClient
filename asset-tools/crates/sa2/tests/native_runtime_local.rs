//! Opt-in comparisons with independent owner-local SA3D/Blender outputs.
//! Original resources and generated oracle values are never embedded in Git.
use sa2_asset_tools::{collision, manifest, model, motion, pose, stage};
use serde_json::Value;
use std::{
    collections::BTreeMap,
    fs,
    path::{Path, PathBuf},
};

fn reference_root() -> PathBuf {
    PathBuf::from(
        std::env::var_os("SA2_REFERENCE_ROOT")
            .expect("set SA2_REFERENCE_ROOT to the original checkout containing .local"),
    )
}
fn matrix(reference: &Value) -> [[f64; 4]; 4] {
    std::array::from_fn(|row| {
        std::array::from_fn(|column| reference[row][column].as_f64().unwrap())
    })
}
fn compare_nodes(actual: &[pose::EvaluatedNode], reference: &Value, native: &[model::Node]) -> f64 {
    let expected = reference.as_array().unwrap();
    assert_eq!(actual.len(), expected.len());
    assert_eq!(actual.len(), native.len());
    let mut maximum = 0f64;
    for (index, (actual, expected)) in actual.iter().zip(expected).enumerate() {
        assert_eq!(actual.offset, native[index].offset);
        assert_eq!(actual.flags as u64, expected["flags"].as_u64().unwrap());
        let parent = expected["parentIndex"]
            .as_u64()
            .map(|i| native[i as usize].offset);
        assert_eq!(actual.parent_offset, parent);
        for (name, actual) in [
            ("localMatrix", &actual.local_matrix),
            ("worldMatrix", &actual.world_matrix),
        ] {
            let expected = matrix(&expected[name]);
            for row in 0..4 {
                for column in 0..4 {
                    let error = (actual[row][column] - expected[row][column]).abs();
                    maximum = maximum.max(error);
                    assert!(
                        error <= 2e-5,
                        "node {index} {name}[{row}][{column}] error {error}: {} != {}",
                        actual[row][column],
                        expected[row][column]
                    );
                }
            }
        }
    }
    maximum
}

#[test]
#[ignore = "requires SA2_NATIVE_POSE_REFERENCE generated by reference-native-pose.py and original SA2_REFERENCE_ROOT"]
fn original_chao_pose_sampling_matches_independent_sa3d() {
    let root = reference_root();
    let oracle_path = PathBuf::from(
        std::env::var_os("SA2_NATIVE_POSE_REFERENCE")
            .expect("set SA2_NATIVE_POSE_REFERENCE to a fresh ignored SA3D oracle JSON"),
    );
    let oracle_bytes = fs::read(&oracle_path).unwrap();
    let oracle: Value = serde_json::from_slice(&oracle_bytes).unwrap();
    assert_eq!(
        oracle["assemblyVersion"],
        "1.2.2+f23c73df68c0c69a96f28746c41b6fc32643340a"
    );
    assert_eq!(oracle["sourceInputsUnchanged"], true);
    let assembly = fs::read(root.join(".local/tools/saio-2.2.2/DLL/SA3D.Modeling.dll")).unwrap();
    assert_eq!(
        manifest::sha256(&assembly),
        oracle["assemblySha256"].as_str().unwrap()
    );
    let script =
        fs::read(Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/reference-native-pose.py"))
            .unwrap();
    assert_eq!(
        manifest::sha256(&script),
        oracle["scriptSha256"].as_str().unwrap(),
        "regenerate oracle after changing its script"
    );
    let records = oracle["models"].as_array().unwrap();
    assert_eq!(records.len(), 7);
    let mut poses = 0;
    let mut maximum_error = 0f64;
    for record in records {
        let source_path = root.join(record["source"].as_str().unwrap());
        let source = fs::read(&source_path).unwrap();
        assert_eq!(
            manifest::sha256(&source),
            record["sha256"].as_str().unwrap()
        );
        let native = model::read_model(&source).unwrap();
        assert_eq!(native.nodes.len(), 40);
        for (node, expected) in native.nodes.iter().zip(record["rest"].as_array().unwrap()) {
            assert_eq!(
                native.labels.get(&node.offset).unwrap(),
                expected["label"].as_str().unwrap()
            );
        }
        let evaluated = pose::evaluate_nodes(&native.nodes).unwrap();
        maximum_error =
            maximum_error.max(compare_nodes(&evaluated, &record["rest"], &native.nodes));
        poses += 1;
        for animation in record["motions"].as_array().unwrap() {
            let path = root.join(animation["source"].as_str().unwrap());
            let bytes = fs::read(&path).unwrap();
            assert_eq!(
                manifest::sha256(&bytes),
                animation["sha256"].as_str().unwrap()
            );
            let motion = motion::read_motion(&bytes).unwrap();
            assert_eq!(
                motion.frame_count as u64,
                animation["frameCount"].as_u64().unwrap()
            );
            for sample in animation["samples"].as_array().unwrap() {
                let requested = sample["requestedFrame"].as_f64().unwrap();
                let evaluated =
                    pose::evaluate_model_pose(&native, Some(&motion), requested).unwrap();
                assert_eq!(evaluated.frame, sample["evaluatedFrame"].as_f64().unwrap());
                assert_eq!(evaluated.frame_count, Some(motion.frame_count));
                maximum_error = maximum_error.max(compare_nodes(
                    &evaluated.nodes,
                    &sample["nodes"],
                    &native.nodes,
                ));
                poses += 1;
            }
            assert_eq!(bytes, fs::read(path).unwrap(), "native motion unchanged");
        }
        assert_eq!(
            source,
            fs::read(source_path).unwrap(),
            "native model unchanged"
        );
        println!(
            "pose model={} sourceSha256={}",
            record["id"], record["sha256"]
        );
    }
    for case in oracle["syntheticRotationOrders"].as_array().unwrap() {
        let vector = |name: &str| std::array::from_fn(|i| case[name][i].as_f64().unwrap() as f32);
        let node = model::Node {
            offset: 1,
            parent_offset: None,
            flags: case["flags"].as_u64().unwrap() as u32,
            attach_offset: 0,
            position: vector("position"),
            rotation_bams: std::array::from_fn(|i| {
                case["rotationBams"][i].as_i64().unwrap() as i32
            }),
            scale: vector("scale"),
            child_offset: 0,
            sibling_offset: 0,
            quaternion_scalar: None,
        };
        let result = pose::evaluate_nodes(&[node]).unwrap();
        let expected = matrix(&case["localMatrix"]);
        for (row, values) in expected.iter().enumerate() {
            for (column, value) in values.iter().enumerate() {
                assert!(
                    (result[0].local_matrix[row][column] - value).abs() < 2e-6,
                    "legacy noncommuting rotation order flags={}",
                    case["flags"]
                );
            }
        }
    }
    assert_eq!(poses, 133);
    println!("independent native pose parity: models=7 poses={poses} nodeTransforms={} maxAbsoluteMatrixError={maximum_error} oracleSha256={}", poses*40, manifest::sha256(&oracle_bytes));
}

fn point(value: &Value) -> [f64; 3] {
    std::array::from_fn(|i| value[i].as_f64().unwrap())
}
fn close(a: [f64; 3], b: [f64; 3], tolerance: f64) -> bool {
    (0..3).all(|i| (a[i] - b[i]).abs() <= tolerance)
}
type Triangle = [[f64; 3]; 3];
fn same_oriented_triangle(a: &Triangle, b: &Triangle) -> bool {
    (0..3).any(|rotation| (0..3).all(|i| close(a[i], b[(i + rotation) % 3], 5e-5)))
}
fn reference_triangles(mesh: &Value) -> Vec<Triangle> {
    let vertices = mesh["vertices"].as_array().unwrap();
    mesh["triangles"]
        .as_array()
        .unwrap()
        .iter()
        .map(|triangle| {
            std::array::from_fn(|i| point(&vertices[triangle[i].as_u64().unwrap() as usize]))
        })
        .collect()
}
fn subtract(a: [f64; 3], b: [f64; 3]) -> [f64; 3] {
    std::array::from_fn(|i| a[i] - b[i])
}
fn cross(a: [f64; 3], b: [f64; 3]) -> [f64; 3] {
    [
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    ]
}

/// Independent vertical-height oracle: solve the 2-D projected triangle and
/// interpolate its plane height. Production uses a general 3-D ray algorithm.
fn reference_height(triangles: &[Triangle], x: f64, z: f64) -> Option<(f64, f64, f64)> {
    let mut highest: Option<(f64, f64, f64)> = None;
    for triangle in triangles {
        let [a, b, c] = *triangle;
        let denominator = (b[0] - a[0]) * (c[2] - a[2]) - (b[2] - a[2]) * (c[0] - a[0]);
        if denominator.abs() < 1e-12 {
            continue;
        }
        let u = ((x - a[0]) * (c[2] - a[2]) - (z - a[2]) * (c[0] - a[0])) / denominator;
        let v = ((b[0] - a[0]) * (z - a[2]) - (b[2] - a[2]) * (x - a[0])) / denominator;
        if u >= -1e-10 && v >= -1e-10 && u + v <= 1.0 + 1e-10 {
            let y = a[1] + u * (b[1] - a[1]) + v * (c[1] - a[1]);
            let normal = cross(subtract(b, a), subtract(c, a));
            let normal_length = (normal.iter().map(|v| v * v).sum::<f64>()).sqrt();
            let candidate = (y, normal[1] / normal_length, u.min(v).min(1.0 - u - v));
            if highest.is_none_or(|old| y > old.0) {
                highest = Some(candidate);
            }
        }
    }
    highest
}

#[test]
#[ignore = "requires original race/Karate native landtables and independently converted Blender collision JSON"]
fn race_and_karate_world_collision_matches_independent_blender() {
    let root = reference_root();
    let mut total_triangles = 0;
    let mut total_queries = 0;
    let mut total_unstable_queries = 0;
    for name in ["race-normal", "race-hero", "race-dark", "karate-arena"] {
        let path = root.join(format!(".local/activities/{name}-collision.json"));
        let reference_bytes = fs::read(&path).unwrap();
        let reference: Value = serde_json::from_slice(&reference_bytes).unwrap();
        assert_eq!(reference["version"], 1);
        assert_eq!(reference["scale"].as_f64().unwrap(), 0.1);
        let source_path = root.join(reference["source"].as_str().unwrap().replace('\\', "/"));
        let source = fs::read(&source_path).unwrap();
        let stage = stage::read_stage(&source).unwrap();
        let world = collision::bake_stage(&stage, 0.1).unwrap();
        let expected = reference["meshes"].as_array().unwrap();
        assert_eq!(world.meshes.len(), expected.len(), "{name} mesh count");
        let mut by_entry = BTreeMap::<usize, Vec<&collision::CollisionMesh>>::new();
        for mesh in &world.meshes {
            by_entry.entry(mesh.entry_index).or_default().push(mesh);
        }
        let mut solid_triangles = Vec::new();
        let mut maximum_vertex_error = 0f64;
        for mesh in expected {
            let label = mesh["name"].as_str().unwrap();
            let entry_index: usize = label.split('_').next().unwrap().parse().unwrap();
            let actual_meshes = by_entry
                .get(&entry_index)
                .unwrap_or_else(|| panic!("{name}: missing source entry {label}"));
            let actual_vertices = actual_meshes
                .iter()
                .flat_map(|mesh| mesh.vertices.iter().copied())
                .collect::<Vec<_>>();
            let expected_vertices = mesh["vertices"]
                .as_array()
                .unwrap()
                .iter()
                .map(point)
                .collect::<Vec<_>>();
            for p in &actual_vertices {
                let nearest_error = expected_vertices
                    .iter()
                    .map(|q| (0..3).map(|i| (p[i] - q[i]).abs()).fold(0f64, f64::max))
                    .fold(f64::INFINITY, f64::min);
                maximum_vertex_error = maximum_vertex_error.max(nearest_error);
                assert!(
                    expected_vertices.iter().any(|q| close(*p, *q, 5e-5)),
                    "{name} {label}: unexpected world vertex {p:?}"
                );
            }
            for p in &expected_vertices {
                assert!(
                    actual_vertices.iter().any(|q| close(*p, *q, 5e-5)),
                    "{name} {label}: missing world vertex {p:?}"
                );
            }
            let triangles = reference_triangles(mesh);
            let actual_triangles = actual_meshes
                .iter()
                .flat_map(|mesh| {
                    mesh.triangles
                        .iter()
                        .map(|indices| indices.map(|i| mesh.vertices[i as usize]))
                })
                .collect::<Vec<_>>();
            assert_eq!(
                actual_triangles.len(),
                triangles.len(),
                "{name} {label}: triangle count"
            );
            let mut used = vec![false; triangles.len()];
            for triangle in &actual_triangles {
                let matched = triangles.iter().enumerate().find(|(i, reference)| {
                    !used[*i] && same_oriented_triangle(triangle, reference)
                });
                let index = matched.unwrap_or_else(||panic!("{name} {label}: world triangle/winding missing in independent reference: {triangle:?}")).0;
                used[index] = true;
            }
            total_triangles += triangles.len();
            for actual in actual_meshes {
                assert_eq!(
                    actual.surface_flags & collision::SURFACE_SOLID != 0,
                    mesh["flags"]["sf_solid"].as_bool().unwrap()
                );
                assert_eq!(
                    actual.surface_flags & collision::SURFACE_DYNAMIC_COLLISION != 0,
                    mesh["flags"]["sf_dynamic_collision"].as_bool().unwrap()
                );
            }
            if mesh["flags"]["sf_solid"] == true && mesh["flags"]["sf_dynamic_collision"] == false {
                solid_triangles.extend(triangles);
            }
        }
        let bound = world.bounds.unwrap();
        for i in 0..3 {
            assert!((bound.min[i] - reference["bounds"]["min"][i].as_f64().unwrap()).abs() < 5e-5);
            assert!((bound.max[i] - reference["bounds"]["max"][i].as_f64().unwrap()).abs() < 5e-5);
        }
        let probes = solid_triangles
            .iter()
            .filter(|triangle| {
                let n = cross(
                    subtract(triangle[1], triangle[0]),
                    subtract(triangle[2], triangle[0]),
                );
                n[1] > 1e-10
            })
            .collect::<Vec<_>>();
        assert!(!probes.is_empty(), "{name} original upward solid surfaces");
        let stride = (probes.len() / 64).max(1);
        let mut queries = 0;
        let mut unstable_queries = 0;
        let mut maximum_height_error = 0f64;
        for triangle in probes.iter().step_by(stride).take(64) {
            let x = (triangle[0][0] + triangle[1][0] + triangle[2][0]) / 3.0;
            let z = (triangle[0][2] + triangle[1][2] + triangle[2][2]) / 3.0;
            let (expected_y, upness, minimum_barycentric) =
                reference_height(&solid_triangles, x, z).unwrap();
            // The Blender receipt rounds float32 world positions. Nearvertical
            // faces and triangle edges amplify that error into unstable height
            // or inside/outside comparisons. Geometry/winding above still
            // checks every source surface; only this query comparator selects
            // stable upward interiors, and reports the excluded probe count.
            if upness < 0.3 || minimum_barycentric < 0.02 {
                unstable_queries += 1;
                continue;
            }
            let hit = world
                .raycast([x, bound.max[1] + 10.0, z], [0.0, -3.0, 0.0], 10_000.0)
                .unwrap()
                .unwrap();
            assert!(
                (hit.position[1] - expected_y).abs() < 1e-4,
                "{name} ray height {} != {expected_y}",
                hit.position[1]
            );
            maximum_height_error = maximum_height_error.max((hit.position[1] - expected_y).abs());
            assert!((hit.distance - (bound.max[1] + 10.0 - expected_y)).abs() < 1e-4);
            assert!(close(hit.position, [x, expected_y, z], 1e-4));
            queries += 1;
        }
        total_queries += queries;
        total_unstable_queries += unstable_queries;
        assert!(
            queries > 0,
            "{name} must exercise stable native upward surfaces"
        );
        assert_eq!(
            source,
            fs::read(source_path).unwrap(),
            "native landtable unchanged"
        );
        assert_eq!(
            reference_bytes,
            fs::read(&path).unwrap(),
            "Blender reference unchanged"
        );
        println!("collision {name}: meshes={} triangles={} stableVerticalQueries={queries} excludedNearVerticalOrEdgeQueries={unstable_queries} maxVertexCoordinateError={maximum_vertex_error} maxStableHeightError={maximum_height_error} sourceSha256={} referenceSha256={}", world.meshes.len(), world.meshes.iter().map(|m|m.triangles.len()).sum::<usize>(), manifest::sha256(&source), manifest::sha256(&reference_bytes));
    }
    assert_eq!(total_triangles, 2_898);
    println!(
        "independent collision parity: triangles={total_triangles} stableVerticalQueries={total_queries} excludedNearVerticalOrEdgeQueries={total_unstable_queries}"
    );
}
