//! sa2-recomp dol MAIN.DOL SYMBOLS.TXT OUT_DIR
//!
//! Writes a Rust crate (sa2-recomp-gen) with one function per game function.
//! OUT_DIR must be under the ignored `.local` folder: the output is derived
//! from the game's code and never goes in git.

use sa2_recomp::{dol, gen};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use std::path::Path;

use sa2_recomp::relgen as rels;

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let r = match (args.get(1).map(String::as_str), args.len()) {
        (Some("dol"), 5) => run(Path::new(&args[2]), Path::new(&args[3]), Path::new(&args[4])),
        (Some("rels"), 6) => rels::run(Path::new(&args[2]), Path::new(&args[3]), Path::new(&args[4]), Path::new(&args[5])),
        (Some("host"), 5) => host(Path::new(&args[2]), Path::new(&args[3]), Path::new(&args[4])),
        _ => {
            eprintln!("usage: sa2-recomp dol MAIN.DOL SYMBOLS.TXT OUT_DIR\n       sa2-recomp rels DISC_REL_DIR STEAM_GD_PC_DIR DECOMP_CONFIG_GSNE8P OUT_DIR\n       sa2-recomp host MAIN_CRATE RELS_CRATE OUT_DIR");
            std::process::exit(2);
        }
    };
    if let Err(e) = r {
        eprintln!("sa2-recomp: {e}");
        std::process::exit(1);
    }
}

const PER_FILE: usize = 150;

/// Write the `sa2-host` crate: links the generated main.dol and REL crates
/// into `sa2_recomp::host`. Run it as `sa2-host MAIN.DOL SYMBOLS.TXT [CALLS]`.
fn host(main_crate: &Path, rels_crate: &Path, out: &Path) -> Result<(), String> {
    let p = |x: &Path| std::path::absolute(x).map(|a| a.display().to_string().replace('\\', "/")).map_err(|e| e.to_string());
    let me = Path::new(env!("CARGO_MANIFEST_DIR")).display().to_string().replace('\\', "/");
    let toml = format!(
        "[package]\nname = \"sa2-host\"\nversion = \"0.0.0\"\nedition = \"2021\"\npublish = false\n\n[workspace]\n\n\
         [dependencies]\nsa2-recomp = {{ path = \"{me}\" }}\nsa2-recomp-gen = {{ path = \"{}\" }}\nsa2-recomp-rels = {{ path = \"{}\" }}\n",
        p(main_crate)?,
        p(rels_crate)?
    );
    let main = "//! Generated by sa2-recomp. Do not commit.\n\
        fn main() {\n\
        \x20   let a: Vec<String> = std::env::args().collect();\n\
        \x20   if a.len() < 3 {\n\
        \x20       eprintln!(\"usage: sa2-host MAIN.DOL SYMBOLS.TXT [CALLS]\");\n\
        \x20       std::process::exit(2);\n\
        \x20   }\n\
        \x20   let dol = std::fs::read(&a[1]).expect(\"read main.dol\");\n\
        \x20   let syms = std::fs::read_to_string(&a[2]).unwrap_or_default();\n\
        \x20   let budget = a.get(3).and_then(|s| s.parse().ok()).unwrap_or(100_000_000);\n\
        \x20   std::panic::set_hook(Box::new(|_| {}));\n\
        \x20   let r = sa2_recomp::host::run(&dol, sa2_recomp_gen::dispatch, sa2_recomp_rels::register, budget).expect(\"host\");\n\
        \x20   sa2_recomp::host::print(&r, &syms);\n\
        }\n";
    std::fs::create_dir_all(out.join("src")).map_err(|e| e.to_string())?;
    std::fs::write(out.join("Cargo.toml"), toml).map_err(|e| e.to_string())?;
    std::fs::write(out.join("src/main.rs"), main).map_err(|e| e.to_string())?;
    println!("wrote {}", out.display());
    Ok(())
}

fn run(dol_path: &Path, sym_path: &Path, out: &Path) -> Result<(), String> {
    let bytes = std::fs::read(dol_path).map_err(|e| format!("{}: {e}", dol_path.display()))?;
    let dol = dol::Dol::parse(&bytes)?;
    let syms = std::fs::read_to_string(sym_path).map_err(|e| format!("{}: {e}", sym_path.display()))?;
    let text: Vec<&dol::Section> = dol.sections.iter().filter(|s| s.text).collect();
    let in_text = |a: u32| text.iter().any(|s| (s.addr..s.addr + s.data.len() as u32).contains(&a));

    // Function starts and ends from symbols.txt (size 0 = up to the next start).
    let mut starts: BTreeMap<u32, (String, u32)> = BTreeMap::new();
    for s in dol::parse_symbols(&syms) {
        if s.function && in_text(s.addr) {
            starts.entry(s.addr).or_insert((s.name, s.size));
        }
    }
    let ranges: Vec<(u32, u32)> = text.iter().map(|s| (s.addr, s.addr + s.data.len() as u32)).collect();
    let sizes = starts.iter().map(|(a, (_, n))| (*a, *n)).collect();
    let funcs: Vec<(u32, u32, String)> = gen::layout(sizes, &ranges, |a| dol.word(a), |_| false)
        .into_iter()
        .map(|(a, end)| (a, end, starts.get(&a).map_or_else(|| format!("fn_{a:08X}"), |s| s.0.clone())))
        .collect();
    let added = funcs.len() - starts.len();
    let starts: BTreeSet<u32> = funcs.iter().map(|f| f.0).collect();

    // Jump-table entries (and other code pointers) stored in data sections.
    let mut extra: BTreeMap<u32, BTreeSet<u32>> = BTreeMap::new();
    for s in dol.sections.iter().filter(|s| !s.text) {
        for w in s.data.chunks_exact(4) {
            let v = u32::from_be_bytes(w.try_into().unwrap());
            if v % 4 == 0 && in_text(v) {
                if let Some(&f) = starts.range(..=v).next_back() {
                    extra.entry(f).or_default().insert(v);
                }
            }
        }
    }

    std::fs::create_dir_all(out.join("src")).map_err(|e| e.to_string())?;
    let mut lib = String::from(
        "//! Generated by sa2-recomp from the local GSNE8P main.dol. Do not commit.\n\
         #![allow(unused_assignments, unreachable_code, unused_variables, unused_mut, unused_braces, non_snake_case, clippy::all)]\n\
         use sa2_recomp::rt::Func;\n",
    );
    let mut dispatch = String::from("pub fn dispatch(a: u32) -> Option<Func> {\n    match a {\n");
    let mut unknown_total = 0;
    let mut unknown_ops: BTreeMap<u32, usize> = BTreeMap::new();
    let mut calls_missing = BTreeSet::new();
    for (part, chunk) in funcs.chunks(PER_FILE).enumerate() {
        let mut src = String::from("use sa2_recomp::rt::{self, *};\n\n");
        for (a, end, name) in chunk {
            let words: Vec<u32> = (*a..*end).step_by(4).map(|x| dol.word(x).unwrap_or(0)).collect();
            let ctx = gen::Ctx { start: *a, end: *end, ..Default::default() };
            for (i, &w) in words.iter().enumerate() {
                let pc = a + 4 * i as u32;
                if gen::translate(w, pc, &ctx).unknown {
                    *unknown_ops.entry(w >> 26).or_default() += 1;
                }
                if w >> 26 == 18 && w & 3 == 1 {
                    let li = ((w & 0x03FF_FFFC) << 6) as i32 >> 6;
                    let t = pc.wrapping_add(li as u32);
                    if !starts.contains(&t) {
                        calls_missing.insert(t);
                    }
                }
            }
            let (code, unknown) = gen::function(name, &ctx, &words, extra.get(a).unwrap_or(&BTreeSet::new()));
            unknown_total += unknown;
            src.push_str(&code);
            src.push('\n');
            let _ = writeln!(dispatch, "        {a:#010x} => Some(p{part}::f_{a:08X}),");
        }
        std::fs::write(out.join(format!("src/p{part}.rs")), src).map_err(|e| e.to_string())?;
        let _ = writeln!(lib, "pub mod p{part};");
    }
    dispatch.push_str("        _ => None,\n    }\n}\n");
    lib.push_str(&dispatch);
    std::fs::write(out.join("src/lib.rs"), lib).map_err(|e| e.to_string())?;
    let me = Path::new(env!("CARGO_MANIFEST_DIR")).display().to_string().replace('\\', "/");
    let toml = format!(
        "[package]\nname = \"sa2-recomp-gen\"\nversion = \"0.0.0\"\nedition = \"2021\"\npublish = false\n\n\
         [workspace]\n\n[dependencies]\nsa2-recomp = {{ path = \"{me}\" }}\n\n\
         [profile.dev]\nopt-level = 1\n"
    );
    std::fs::write(out.join("Cargo.toml"), toml).map_err(|e| e.to_string())?;
    println!(
        "functions {} ({added} added from branch targets) | unknown instructions {unknown_total} {:?} | bl targets without a function {}",
        funcs.len(),
        unknown_ops,
        calls_missing.len()
    );
    Ok(())
}
